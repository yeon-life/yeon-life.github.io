window.YL_findPersona = function(slug){
  return (window.YL_PERSONAS || []).find(p => p.slug === slug) || null;
};
window.YL_findPost = function(slug, postId){
  const p = window.YL_findPersona(slug);
  if (!p) return null;
  return (p.posts || []).find(x => x.id === postId) || null;
};
